<?php

/**
 * The harness's composer.json and phpunit.xml: omniscient/omnidocs from its checkout, each provider from
 * its checkout under /omnidocs/plugins when there is one (a path repository), from GitHub otherwise.
 * Files are rewritten only when they change, so the entrypoint knows when to install.
 */
$core = '/omnidocs/core';
$plugins = '/omnidocs/plugins';
$out = '/harness';
$providers = ['markdown' => 'omnidocs-markdown', 'php' => 'omnidocs-php', 'jsdoc' => 'omnidocs-jsdoc', 'sphinx' => 'omnidocs-sphinx', 'doxygen' => 'omnidocs-doxygen'];

$repositories = [['type' => 'path', 'url' => $core, 'options' => ['symlink' => true, 'versions' => ['omniscient/omnidocs' => '1.x-dev']]]];
$require = ['php' => '>=8.2', 'omniscient/omnidocs' => '1.x-dev'];
$autoload = ['Omnidocs\\Tests\\' => "$core/Tests/"];
$suites = ['omnidocs' => "$core/Tests"];
foreach ($providers as $name => $repository) {
    $package = 'omnidocs/'.$name;
    $namespace = 'Omnidocs\\'.ucfirst($name).'\\Tests\\';
    if (is_file("$plugins/$name/composer.json")) {
        $repositories[] = ['type' => 'path', 'url' => "$plugins/$name", 'options' => ['symlink' => true, 'versions' => [$package => '1.x-dev']]];
        $autoload[$namespace] = "$plugins/$name/Tests/";
        $suites[$name] = "$plugins/$name/Tests";
    } else {
        $repositories[] = ['type' => 'vcs', 'url' => "https://github.com/glitchr-studio/$repository.git", 'no-api' => true];
        $autoload[$namespace] = "vendor/$package/Tests/";
        $suites[$name] = "vendor/$package/Tests";
    }
    $require[$package] = '1.x-dev';
}

$composer = [
    'name' => 'omniscient/omnidocs-harness',
    'description' => 'omniscient/omnidocs and its providers from their checkouts: generated by docker/harness/setup.php, do not edit.',
    'type' => 'project',
    'license' => 'MIT',
    'repositories' => $repositories,
    'require' => $require,
    'require-dev' => ['phpunit/phpunit' => '^11.0'],
    'autoload-dev' => ['psr-4' => $autoload],
    'minimum-stability' => 'dev',
    'prefer-stable' => true,
    'config' => ['sort-packages' => true, 'preferred-install' => ['omnidocs/*' => 'source', '*' => 'dist']],
];
$json = json_encode($composer, \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES)."\n";
if (!is_file("$out/composer.json") || file_get_contents("$out/composer.json") !== $json) {
    file_put_contents("$out/composer.json", $json);
    echo "composer.json composed\n";
}

$xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<phpunit xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xsi:noNamespaceSchemaLocation=\"vendor/phpunit/phpunit/phpunit.xsd\" bootstrap=\"vendor/autoload.php\" colors=\"true\" failOnWarning=\"true\" cacheDirectory=\".phpunit.cache\">\n    <testsuites>\n";
foreach ($suites as $name => $dir) {
    $xml .= "        <testsuite name=\"$name\"><directory>$dir</directory></testsuite>\n";
}
$xml .= "    </testsuites>\n</phpunit>\n";
if (!is_file("$out/phpunit.xml") || file_get_contents("$out/phpunit.xml") !== $xml) {
    file_put_contents("$out/phpunit.xml", $xml);
}
